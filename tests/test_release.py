    def test_release_builder_cannot_package_repository_or_runtime_extras(self):
        spec = importlib.util.spec_from_file_location("libredisplay_release_builder_test", ROOT / "scripts" / "build-release.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        with tempfile.TemporaryDirectory(prefix="libredisplay-minimal-builder-") as td:
            workspace = Path(td) / "repo"
            workspace.mkdir()
            for name in module.TOP_FILES:
                (workspace / name).write_text("1.8.1\n" if name == "VERSION" else f"{name}\n", encoding="utf-8")
            for dirname in module.TOP_DIRS:
                (workspace / dirname).mkdir()
                (workspace / dirname / "project.txt").write_text("project\n", encoding="utf-8")
            for name in ("CHANGELOG.md", "CONTRIBUTING.md", "SECURITY.md", ".env.example", ".env", ".gitignore", ".dockerignore"):
                (workspace / name).write_text("do not ship\n", encoding="utf-8")
            (workspace / ".github").mkdir()
            (workspace / ".github" / "ci.yml").write_text("do not ship\n", encoding="utf-8")
            for dirname in ("data", "media", "backups", ".venv", ".libredisplay-update"):
                d = workspace / dirname
                d.mkdir()
                (d / "private.txt").write_text("secret\n", encoding="utf-8")
            (workspace / "private.ldbackup").write_text("secret\n", encoding="utf-8")
            output = Path(td) / "LibreDisplay-v1.8.1.zip"
            old_root = module.ROOT
            try:
                module.ROOT = workspace
                module.build(output)
            finally:
                module.ROOT = old_root
            with zipfile.ZipFile(output) as archive:
                names = set(archive.namelist())
            prefix = "LibreDisplay-1.8.1/"
            self.assertIn(prefix + "README.md", names)
            for dirname in module.TOP_DIRS:
                self.assertIn(prefix + dirname + "/project.txt", names)
            for forbidden in ("CHANGELOG.md", "CONTRIBUTING.md", "SECURITY.md", ".env.example", ".env", ".gitignore", ".dockerignore", ".github/ci.yml", "data/private.txt", "media/private.txt", "backups/private.txt", ".venv/private.txt", ".libredisplay-update/private.txt", "private.ldbackup"):
                self.assertNotIn(prefix + forbidden, names)

