    def test_public_tree_has_no_private_working_artifacts(self):
        forbidden_name_fragments = ("scratch", "checkpoint", "release-readiness-audit")
        for path in ROOT.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(ROOT)
            lower_name = path.name.lower()
            self.assertFalse(any(fragment in lower_name for fragment in forbidden_name_fragments), f"private working note in release tree: {rel}")


    def test_public_tree_has_no_assistant_or_generated_working_notes(self):
        forbidden = (
            "generated by " + "chat" + "gpt", "chat" + "gpt" + " note", "open" + "ai" + " assistant", "assistant" + " note:",
            "a" + "i-" + "generated", "a" + "i " + "generated", "as an " + "a" + "i", "chain of " + "thought",
            "clau" + "de" + " generated", "co" + "pilot" + " generated", "gem" + "ini" + " generated",
        )
        text_suffixes = {".py", ".js", ".mjs", ".sh", ".html", ".css", ".md", ".txt", ".yml", ".yaml", ".json"}
        offenders = []
        for path in ROOT.rglob("*"):
            if not path.is_file() or path.suffix.lower() not in text_suffixes:
                continue
            text = path.read_text(encoding="utf-8", errors="ignore").lower()
            for phrase in forbidden:
                if phrase in text:
                    offenders.append(f"{path.relative_to(ROOT)}: {phrase}")
        self.assertEqual(offenders, [], "assistant/generated working notes leaked into release tree: " + ", ".join(offenders))

